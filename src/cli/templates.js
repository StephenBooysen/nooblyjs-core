/**
 * @fileoverview App templates for `nooblyjs create` (feature 09). Each template
 * returns the files of a minimal app that follows core's conventions: services
 * wired through the registry, API keys from the environment, and a test that
 * runs with the Node test runner (no extra test dependency).
 *
 * @module cli/templates
 */

'use strict';

const TEMPLATES = Object.freeze(['api', 'dashboard', 'ai']);

/**
 * Builds the files for a new app.
 *
 * @param {string} name Package name (lowercase, letters, digits and dashes)
 * @param {string} template One of TEMPLATES
 * @param {string} coreVersion Version range of nooblyjs-core to depend on
 * @return {!Object<string, string>} Relative path → file content
 */
function appFiles(name, template, coreVersion) {
  if (!TEMPLATES.includes(template)) {
    throw new Error(`Unknown template "${template}". Use one of: ${TEMPLATES.join(', ')}`);
  }
  const ai = template === 'ai';
  const dashboard = template === 'dashboard';

  const dependencies = {
    express: '^4.19.2',
    'nooblyjs-core': coreVersion
  };
  const pkg = {
    name,
    version: '0.1.0',
    private: true,
    main: 'app.js',
    engines: { node: '>=22' },
    scripts: {
      start: 'node app.js',
      dev: 'node --watch app.js',
      test: 'node --test'
    },
    dependencies
  };

  const services = [
    "const logger = serviceRegistry.logger('memory');",
    "const cache = serviceRegistry.cache('memory');",
    "const queue = serviceRegistry.queue('memory');",
    "const data = serviceRegistry.dataService('memory');"
  ];
  if (ai) {
    services.push(
      "// AI Service v2: set ANTHROPIC_API_KEY (or switch the provider) in .env.",
      "const ai = serviceRegistry.aiservice(process.env.AI_PROVIDER || 'mock', { legacy: false, apiKey: process.env.ANTHROPIC_API_KEY });"
    );
  }

  const authOptions = dashboard
    ? "servicesAuth: { requireLogin: true }"
    : "servicesAuth: { requireLogin: false }";

  const app = `'use strict';

// ${name}: a NooblyJS app generated by \`nooblyjs create\` (template: ${template}).

const path = require('node:path');
const express = require('express');
const { EventEmitter } = require('node:events');
const serviceRegistry = require('nooblyjs-core');

const app = express();
app.use(express.json({ limit: '1mb' }));

const eventEmitter = new EventEmitter();
serviceRegistry.initialize(app, eventEmitter, {
  logDir: path.join(__dirname, '.application', 'logs'),
  dataDir: path.join(__dirname, '.application', 'data'),
  security: {
    apiKeyAuth: {
      requireApiKey: true,
      apiKeys: (process.env.API_KEYS || '').split(',').map((k) => k.trim()).filter(Boolean)
    },
    ${authOptions}
  }
});

${services.join('\n')}

app.get('/health', (req, res) => res.json({ status: 'ok' }));

const PORT = Number(process.env.PORT) || 9000;
if (require.main === module) {
  app.listen(PORT, () => logger.info(\`${name} listening on port \${PORT}\`));
}

module.exports = { app, serviceRegistry };
`;

  const test = `'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { app } = require('../app');

test('health endpoint answers', async (t) => {
  const server = app.listen(0);
  t.after(() => server.close());
  const { port } = server.address();
  const res = await fetch(\`http://127.0.0.1:\${port}/health\`);
  assert.equal(res.status, 200);
  assert.deepEqual(await res.json(), { status: 'ok' });
});
`;

  const env = `# Copy to .env and fill in. Never commit .env.
# Comma-separated API keys. Generate one with: npx nooblyjs keys generate
API_KEYS=
PORT=9000
SESSION_SECRET=
SETTINGS_SECRET=
${ai ? 'AI_PROVIDER=mock\nANTHROPIC_API_KEY=\n' : ''}`;

  return {
    'package.json': `${JSON.stringify(pkg, null, 2)}\n`,
    'app.js': app,
    'test/app.test.js': test,
    '.env.example': env,
    '.gitignore': 'node_modules/\n.env\n.application/\n.temp/\n',
    'README.md': `# ${name}\n\nGenerated by \`nooblyjs create\` (template: ${template}).\n\n` +
      '```sh\nnpm install\ncp .env.example .env   # set API_KEYS\nnpm test\nnpm start\n```\n\n' +
      'Check the setup with `npx nooblyjs doctor`, and list the API with `npx nooblyjs routes --url http://localhost:9000 --key $API_KEY`.\n'
  };
}

module.exports = { appFiles, TEMPLATES };
