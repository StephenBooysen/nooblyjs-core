/**
 * @fileoverview Generates a dependency-free, strictly typed TypeScript client from
 * a NooblyJS OpenAPI document (feature 10 / 09). The client uses `fetch` through
 * an injectable function, so it runs on Node 18+ and in browsers without a
 * framework.
 *
 * Usage in generated code:
 *   const api = new NooblyJSClient({ baseUrl: 'http://localhost:9000', apiKey: '...' });
 *   await api.caching.putCache({ path: { key: 'user:1' }, body: { name: 'Ada' } });
 *
 * @author NooblyJS Team
 * @since 1.0.14
 */

'use strict';

const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'patch'];

/** Makes a valid TypeScript identifier from any string. */
function identifier(name) {
  const cleaned = String(name).replace(/[^A-Za-z0-9_$]+/g, '_').replace(/^(\d)/, '_$1');
  return cleaned || '_';
}

/** Lower-cases the first letter of a tag, e.g. "Caching" -> "caching". */
function groupName(tag) {
  const id = identifier(tag);
  return id.charAt(0).toLowerCase() + id.slice(1);
}

/**
 * Generates the client source.
 *
 * @param {Object} doc OpenAPI 3.x document
 * @return {string} TypeScript source
 */
function generateTypeScriptClient(doc) {
  const groups = new Map();
  for (const [route, item] of Object.entries(doc.paths || {})) {
    for (const method of HTTP_METHODS) {
      const op = item[method];
      if (!op) continue;
      const tag = (op.tags && op.tags[0]) || 'Other';
      const group = groupName(tag);
      if (!groups.has(group)) groups.set(group, []);
      groups.get(group).push({ method, route, op, name: identifier(op.operationId || `${method}_${route}`) });
    }
  }

  const lines = [];
  lines.push('// Generated by `nooblyjs openapi --client ts`. Do not edit by hand.');
  lines.push('/* eslint-disable */');
  lines.push('');
  lines.push('export interface NooblyJSFetchResponse {');
  lines.push('  readonly ok: boolean;');
  lines.push('  readonly status: number;');
  lines.push('  text(): Promise<string>;');
  lines.push('}');
  lines.push('');
  lines.push('export type NooblyJSFetch = (');
  lines.push('  input: string,');
  lines.push('  init: { method: string; headers: Record<string, string>; body?: string }');
  lines.push(') => Promise<NooblyJSFetchResponse>;');
  lines.push('');
  lines.push('export interface NooblyJSClientOptions {');
  lines.push('  /** App base URL, e.g. http://localhost:9000 */');
  lines.push('  baseUrl: string;');
  lines.push('  /** Sent as the x-api-key header */');
  lines.push('  apiKey?: string;');
  lines.push('  /** Sent as an Authorization: Bearer header (a personal access token) */');
  lines.push('  bearerToken?: string;');
  lines.push('  /** Replaces the global fetch, for tests or older runtimes */');
  lines.push('  fetch?: NooblyJSFetch;');
  lines.push('}');
  lines.push('');
  lines.push('export interface NooblyJSCallArgs {');
  lines.push('  path?: Record<string, string | number>;');
  lines.push('  query?: Record<string, string | number | boolean | undefined>;');
  lines.push('  body?: unknown;');
  lines.push('}');
  lines.push('');
  lines.push('/** Error for a non-2xx answer. `body` is the parsed JSON answer when there is one. */');
  lines.push('export class NooblyJSApiError extends Error {');
  lines.push('  readonly status: number;');
  lines.push('  readonly body: unknown;');
  lines.push('  constructor(status: number, body: unknown) {');
  lines.push('    super(`NooblyJS API error ${status}`);');
  lines.push('    this.name = "NooblyJSApiError";');
  lines.push('    this.status = status;');
  lines.push('    this.body = body;');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push('type Caller = (method: string, route: string, args?: NooblyJSCallArgs) => Promise<unknown>;');
  lines.push('');
  for (const [group, ops] of groups) {
    lines.push(`class ${identifier(group[0].toUpperCase() + group.slice(1))}Operations {`);
    lines.push('  constructor(private readonly call: Caller) {}');
    for (const o of ops) {
      const summary = (o.op.summary || '').replace(/\*\//g, '');
      lines.push(`  /** ${o.method.toUpperCase()} ${o.route}${summary ? ` - ${summary}` : ''} */`);
      lines.push(`  ${o.name}(args: NooblyJSCallArgs = {}): Promise<unknown> {`);
      lines.push(`    return this.call(${JSON.stringify(o.method.toUpperCase())}, ${JSON.stringify(o.route)}, args);`);
      lines.push('  }');
    }
    lines.push('}');
    lines.push('');
  }

  lines.push('export class NooblyJSClient {');
  for (const group of groups.keys()) {
    lines.push(`  readonly ${group}: ${identifier(group[0].toUpperCase() + group.slice(1))}Operations;`);
  }
  lines.push('  private readonly options: NooblyJSClientOptions;');
  lines.push('');
  lines.push('  constructor(options: NooblyJSClientOptions) {');
  lines.push('    this.options = options;');
  lines.push('    const call: Caller = (method, route, args = {}) => this.request(method, route, args);');
  for (const group of groups.keys()) {
    lines.push(`    this.${group} = new ${identifier(group[0].toUpperCase() + group.slice(1))}Operations(call);`);
  }
  lines.push('  }');
  lines.push('');
  lines.push('  private async request(method: string, route: string, args: NooblyJSCallArgs): Promise<unknown> {');
  lines.push('    let url = route.replace(/\\{([^}]+)\\}/g, (_match, name: string) => encodeURIComponent(String(args.path?.[name] ?? "")));');
  lines.push('    const query = Object.entries(args.query ?? {})');
  lines.push('      .filter(([, value]) => value !== undefined)');
  lines.push('      .map(([key, value]) => `${encodeURIComponent(key)}=${encodeURIComponent(String(value))}`)');
  lines.push('      .join("&");');
  lines.push('    if (query) url += `?${query}`;');
  lines.push('    const headers: Record<string, string> = { accept: "application/json" };');
  lines.push('    if (args.body !== undefined) headers["content-type"] = "application/json";');
  lines.push('    if (this.options.apiKey) headers["x-api-key"] = this.options.apiKey;');
  lines.push('    if (this.options.bearerToken) headers["authorization"] = `Bearer ${this.options.bearerToken}`;');
  lines.push('    const doFetch: NooblyJSFetch = this.options.fetch ?? (globalThis as unknown as { fetch: NooblyJSFetch }).fetch;');
  lines.push('    const response = await doFetch(`${this.options.baseUrl.replace(/\\/$/, "")}${url}`, {');
  lines.push('      method,');
  lines.push('      headers,');
  lines.push('      body: args.body !== undefined ? JSON.stringify(args.body) : undefined');
  lines.push('    });');
  lines.push('    const text = await response.text();');
  lines.push('    const data: unknown = text ? JSON.parse(text) : null;');
  lines.push('    if (!response.ok) throw new NooblyJSApiError(response.status, data);');
  lines.push('    return data;');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

module.exports = { generateTypeScriptClient };
