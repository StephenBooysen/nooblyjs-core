/**
 * @fileoverview Generates a dependency-free typed client from an OpenAPI
 * document (feature 10): one function per operation, grouped by service tag.
 *
 *   const client = createNooblyClient({ baseUrl, apiKey });
 *   await client.caching.putCache('user:1', { body: { name: 'Ann' } });
 *
 * The client has no runtime dependency and needs only `fetch` at run time. It
 * uses a minimal fetch type of its own, so it compiles with `strict` in any
 * project, with or without DOM or Node typings.
 *
 * @module cli/clientgen
 */

'use strict';

const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];

/**
 * Turns an identifier into camelCase. Non-identifier characters separate words.
 * @param {string} text
 * @return {string}
 */
function camel(text) {
  const words = String(text).split(/[^A-Za-z0-9]+/).filter(Boolean);
  let out = words.map((w, i) => (i === 0 ? w.charAt(0).toLowerCase() + w.slice(1) : w.charAt(0).toUpperCase() + w.slice(1))).join('');
  if (!out || /^[0-9]/.test(out)) out = `op${out}`;
  return out;
}

/** Parameter names the generated functions use themselves, so path parameters avoid them. */
const RESERVED = new Set(['options', 'req', 'request', 'path', 'method', 'url', 'body']);

/** The TypeScript parameter name for a path parameter. */
function paramName(name) {
  const c = camel(name);
  return RESERVED.has(c) ? `${c}Param` : c;
}

/** A property name that is safe in an object literal. */
function propName(name) {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

/**
 * Builds the TypeScript source for the document.
 *
 * @param {!Object} doc OpenAPI document
 * @param {{title?: string}=} options
 * @return {string} TypeScript source
 */
function generateTypeScriptClient(doc, options = {}) {
  const groups = new Map();
  const used = new Map();

  for (const [route, item] of Object.entries(doc.paths || {})) {
    for (const method of HTTP_METHODS) {
      const op = item[method];
      if (!op) continue;
      const tag = camel((op.tags && op.tags[0]) || 'platform');
      if (!groups.has(tag)) groups.set(tag, []);
      const params = [...route.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((m) => m[1]);
      let name = camel(op.operationId || `${method}_${route}`);
      const key = `${tag}.${name}`;
      const count = (used.get(key) || 0) + 1;
      used.set(key, count);
      if (count > 1) name = `${name}${count}`;
      const template = route.replace(/\{([A-Za-z0-9_]+)\}/g, (_, p) => `\${encodeURIComponent(${p})}`);
      groups.get(tag).push({
        name,
        method: method.toUpperCase(),
        params,
        template,
        summary: op.summary || '',
        secured: Array.isArray(op.security) && op.security.length > 0
      });
    }
  }

  const lines = [];
  lines.push('// Generated by `nooblyjs openapi --client ts` from the app\'s OpenAPI document. Do not edit by hand.');
  lines.push(`// ${options.title || 'NooblyJS API client'}`);
  lines.push('/* eslint-disable */');
  lines.push('');
  lines.push('export interface NooblyClientOptions {');
  lines.push('  /** Base URL of the app, for example http://localhost:9000 */');
  lines.push('  baseUrl: string;');
  lines.push('  /** API key sent as x-api-key, or a bearer token sent as Authorization */');
  lines.push('  apiKey?: string;');
  lines.push('  /** Replaces the global fetch, for tests and proxies */');
  lines.push('  fetch?: (url: string, init: { method: string; headers: Record<string, string>; body?: string }) => Promise<{ ok: boolean; status: number; text(): Promise<string> }>;');
  lines.push('}');
  lines.push('');
  lines.push('export interface RequestOptions {');
  lines.push('  query?: Record<string, string | number | boolean | undefined>;');
  lines.push('  body?: unknown;');
  lines.push('  headers?: Record<string, string>;');
  lines.push('}');
  lines.push('');
  lines.push('export class NooblyApiError extends Error {');
  lines.push('  readonly status: number;');
  lines.push('  readonly body: unknown;');
  lines.push('  constructor(status: number, body: unknown) {');
  lines.push('    super(`The app answered ${status}`);');
  lines.push('    this.name = "NooblyApiError";');
  lines.push('    this.status = status;');
  lines.push('    this.body = body;');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push('async function request(options: NooblyClientOptions, method: string, path: string, req: RequestOptions = {}): Promise<unknown> {');
  lines.push('  const doFetch = options.fetch ?? (globalThis as unknown as { fetch: NonNullable<NooblyClientOptions["fetch"]> }).fetch;');
  lines.push('  let url = options.baseUrl.replace(/\\/$/, "") + path;');
  lines.push('  const pairs: string[] = [];');
  lines.push('  for (const [key, value] of Object.entries(req.query ?? {})) {');
  lines.push('    if (value !== undefined) pairs.push(`${encodeURIComponent(key)}=${encodeURIComponent(String(value))}`);');
  lines.push('  }');
  lines.push('  if (pairs.length) url += `?${pairs.join("&")}`;');
  lines.push('  const headers: Record<string, string> = { accept: "application/json", ...(req.headers ?? {}) };');
  lines.push('  if (options.apiKey) headers["x-api-key"] = options.apiKey;');
  lines.push('  let body: string | undefined;');
  lines.push('  if (req.body !== undefined) {');
  lines.push('    headers["content-type"] = "application/json";');
  lines.push('    body = JSON.stringify(req.body);');
  lines.push('  }');
  lines.push('  const res = await doFetch(url, { method, headers, body });');
  lines.push('  const text = await res.text();');
  lines.push('  let data: unknown = null;');
  lines.push('  if (text) {');
  lines.push('    try { data = JSON.parse(text); } catch { data = text; }');
  lines.push('  }');
  lines.push('  if (!res.ok) throw new NooblyApiError(res.status, data);');
  lines.push('  return data;');
  lines.push('}');
  lines.push('');
  lines.push('export function createNooblyClient(options: NooblyClientOptions) {');
  lines.push('  return {');
  for (const [tag, ops] of [...groups.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`    ${propName(tag)}: {`);
    for (const op of ops) {
      const args = op.params.map((p) => `${paramName(p)}: string`);
      const sig = [...args, 'req: RequestOptions = {}'].join(', ');
      if (op.summary) lines.push(`      /** ${op.summary.replace(/\*\//g, '* /')} */`);
      lines.push(`      ${propName(op.name)}(${sig}): Promise<unknown> {`);
      const path = op.template.replace(/\$\{encodeURIComponent\((\w+)\)\}/g, (_, p) => `\${encodeURIComponent(${paramName(p)})}`);
      lines.push(`        return request(options, "${op.method}", \`${path}\`, req);`);
      lines.push('      },');
    }
    lines.push('    },');
  }
  lines.push('  };');
  lines.push('}');
  lines.push('');
  lines.push('export type NooblyClient = ReturnType<typeof createNooblyClient>;');
  lines.push('');
  return lines.join('\n');
}

module.exports = { generateTypeScriptClient, camel };
