#!/usr/bin/env node
'use strict';

/**
 * @fileoverview Generates the ESM entry points of nooblyjs-core (feature 14).
 *
 * The package is CommonJS. Each subpath that ESM users import gets a small
 * wrapper in `esm/`, which loads the CommonJS module with createRequire and
 * re-exports it: `default` plus one named export per public key. For the
 * registry, the named exports are its public methods, bound to the singleton.
 *
 *   node scripts/generate-esm.js --write   regenerate esm/*.mjs
 *   node scripts/generate-esm.js --check   fail when the files are out of date
 *
 * @module scripts/generate-esm
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'esm');

/** Entry points: the wrapper file, the CommonJS target, and how to find names. */
const ENTRIES = [
  { file: 'index.mjs', target: '../index.js', kind: 'registry' },
  { file: 'testing.mjs', target: '../testing.js', kind: 'module' },
  { file: 'store.mjs', target: '../src/store/fs-store.js', kind: 'module' },
  { file: 'shell.mjs', target: '../src/shell/index.js', kind: 'module' },
  { file: 'route-pattern.mjs', target: '../src/shared/utils/routePattern.js', kind: 'module' }
];

/** Words that cannot be export names, whatever the module says. */
const RESERVED = new Set([
  'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default', 'delete', 'do', 'else',
  'export', 'extends', 'finally', 'for', 'function', 'if', 'import', 'in', 'instanceof', 'new', 'return',
  'super', 'switch', 'this', 'throw', 'try', 'typeof', 'var', 'void', 'while', 'with', 'yield', 'let',
  'static', 'enum', 'await', 'implements', 'package', 'protected', 'interface', 'private', 'public', 'null', 'true', 'false'
]);

/**
 * Public method names of the registry: prototype methods that are not the
 * constructor and not private (names starting or ending with an underscore).
 * @param {Object} registry
 * @return {string[]}
 */
function registryMethods(registry) {
  const names = new Set();
  for (let proto = Object.getPrototypeOf(registry); proto && proto !== Object.prototype; proto = Object.getPrototypeOf(proto)) {
    for (const name of Object.getOwnPropertyNames(proto)) {
      if (name === 'constructor' || name.startsWith('_') || name.endsWith('_')) continue;
      const descriptor = Object.getOwnPropertyDescriptor(proto, name);
      if (descriptor && typeof descriptor.value === 'function') names.add(name);
    }
  }
  return [...names].sort();
}

/**
 * Renders one wrapper file.
 * @param {Object} entry
 * @return {string}
 */
function render(entry) {
  const target = require(path.join(OUT, entry.target));
  const lines = [
    '// Generated by scripts/generate-esm.js. Do not edit by hand.',
    "import { createRequire } from 'node:module';",
    'const require = createRequire(import.meta.url);',
    `const target = require(${JSON.stringify(entry.target)});`,
    '',
    'export default target;'
  ];
  if (entry.kind === 'registry') {
    for (const name of registryMethods(target)) {
      if (RESERVED.has(name) || !/^[A-Za-z_$][\w$]*$/.test(name)) continue;
      lines.push(`export const ${name} = (...args) => target.${name}(...args);`);
    }
  } else {
    for (const name of Object.keys(target).sort()) {
      if (name === 'default' || RESERVED.has(name) || !/^[A-Za-z_$][\w$]*$/.test(name)) continue;
      lines.push(`export const ${name} = target.${name};`);
    }
  }
  return `${lines.join('\n')}\n`;
}

function main() {
  const mode = process.argv[2];
  if (mode !== '--write' && mode !== '--check') {
    process.stderr.write('usage: generate-esm.js --write | --check\n');
    process.exit(2);
  }
  const drift = [];
  for (const entry of ENTRIES) {
    const file = path.join(OUT, entry.file);
    const content = render(entry);
    if (mode === '--write') {
      fs.mkdirSync(OUT, { recursive: true });
      fs.writeFileSync(file, content);
    } else if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) {
      drift.push(entry.file);
    }
  }
  if (drift.length) {
    process.stderr.write(`esm wrappers out of date: ${drift.join(', ')}. Run: npm run build:esm\n`);
    process.exit(1);
  }
  process.stdout.write(mode === '--write' ? 'esm wrappers written\n' : 'esm wrappers up to date\n');
}

if (require.main === module) main();

module.exports = { ENTRIES, registryMethods, render };
